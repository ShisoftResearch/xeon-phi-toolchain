#!/usr/bin/env python3
"""Independent round-to-nearest-even IEEE oracle using exact rational arithmetic."""
from phi_common import RECORDS
RECORDS.mkdir(parents=True,exist_ok=True)
from fractions import Fraction
import json, pathlib, random, struct, math
root=pathlib.Path(__file__).resolve().parents[1]
from ieee_oracle import decode, round_bits

def operate(a,b,op,w):
 f,e=(23,8) if w==32 else (52,11);inf=((1<<e)-1)<<f;nan=inf|(1<<(f-1))
 sa,ta,va=decode(a,w);sb,tb,vb=decode(b,w)
 if op==5:
  if ta=='nan' or (sa and (ta=='inf' or va)):return nan
  if ta=='inf':return inf
  if not va:return a
  n,d=va.numerator,va.denominator;k=n.bit_length()-d.bit_length()
  if (n < d<<k) if k>=0 else (n<<-k < d):k-=1
  exponent=k//2;step=exponent-f
  nn,dd=(n,d<<(2*step)) if step>=0 else (n<<(-2*step),d)
  q=math.isqrt(nn//dd);diff=4*nn-dd*(2*q+1)**2
  if diff>0 or (diff==0 and q&1):q+=1
  if q>=1<<(f+1):q>>=1;exponent+=1
  bias=(1<<(e-1))-1
  return ((exponent+bias)<<f)|(q-(1<<f))
 if op==4:
  if ta=='nan' or tb=='nan':return b
  if ta=='inf':less=bool(sa) and not(tb=='inf' and sb)
  elif tb=='inf':less=not bool(sb)
  else:less=va<vb
  return a if less else b
 if ta=='nan' or tb=='nan':return nan
 if op==1:sb^=1;vb=-vb if vb is not None else None
 if op in (0,1):
  if ta=='inf' and tb=='inf' and sa!=sb:return nan
  if ta=='inf':return (sa<<(w-1))|inf
  if tb=='inf':return (sb<<(w-1))|inf
  return round_bits(va+vb,w,int(not va and not vb and sa and sb))
 sign=sa^sb
 if op==2:
  if (ta=='inf' and tb=='finite' and not vb) or (tb=='inf' and ta=='finite' and not va):return nan
  if ta=='inf' or tb=='inf':return (sign<<(w-1))|inf
  return round_bits(va*vb,w,sign)
 if ta=='inf' and tb=='inf':return nan
 if ta=='inf':return (sign<<(w-1))|inf
 if tb=='inf':return sign<<(w-1)
 if not vb:return ((sign<<(w-1))|inf) if va else nan
 return round_bits(va/vb,w,sign)
# Check the oracle independently against hardware binary64 for finite nonzero values.
rng=random.Random(5301);checked=0
for _ in range(3000):
 a,b=rng.getrandbits(64),rng.getrandbits(64);_,ta,va=decode(a,64);_,tb,vb=decode(b,64)
 if ta!='finite' or tb!='finite' or not va or not vb:continue
 af,bf=struct.unpack('<d',struct.pack('<Q',a))[0],struct.unpack('<d',struct.pack('<Q',b))[0]
 for op,fn in enumerate([lambda:af+bf,lambda:af-bf,lambda:af*bf,lambda:af/bf]):
  ref=struct.unpack('<Q',struct.pack('<d',fn()))[0];assert operate(a,b,op,64)==ref,(a,b,op);checked+=1
out=['/* Generated by generate-fp-corpus.py: exact rational IEEE round-to-nearest-even oracle. */','struct fp64_case {uint64_t a,b,expected;unsigned op,nan;};','struct fp32_case {uint32_t a,b,expected;unsigned op,nan;};'];counts={}
for w in [64,32]:
 f,e=(23,8) if w==32 else (52,11);inf=((1<<e)-1)<<f;sign=1<<(w-1)
 edges=[0,sign,1,sign|1,(1<<f)-1,1<<f,sign|(1<<f),((1<<(e-1))-1)<<f,sign|(((1<<(e-1))-1)<<f),inf-1,sign|(inf-1),inf,sign|inf,inf|1,inf|(1<<(f-1)),sign|inf|123]
 pairs=[(a,b) for a in edges for b in edges]+[(rng.getrandbits(w),rng.getrandbits(w)) for _ in range(500)]
 out.append(f'static const struct fp{w}_case fp{w}_cases[] = {{');count=0
 for a,b in pairs:
  for op in range(6):
   expected=operate(a,b,op,w);isnan=int(decode(expected,w)[1]=='nan')
   suffix='ULL' if w==64 else 'U';out.append(f'{{0x{a:x}{suffix},0x{b:x}{suffix},0x{expected:x}{suffix},{op},{isnan}}},');count+=1
 out.append('};');counts[w]=count
(root/'tests/fp-corpus.h').write_text('\n'.join(out)+'\n')
(RECORDS/'fp-oracle.json').write_text(json.dumps({'method':'exact rational arithmetic with IEEE nearest-even rounding','independent_binary64_crosschecks':checked,'cases':counts},indent=2)+'\n')
print('Generated',counts,'cases; independent binary64 crosschecks:',checked)
