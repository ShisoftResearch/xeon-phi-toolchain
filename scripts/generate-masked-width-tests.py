#!/usr/bin/env python3
"""Generate semantic masked-memory matrix declarations and LLVM regression IR."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
types=[('i8','i8',1),('i16','i16',2),('i32','i32',4),('i64','i64',8),('f32','float',4),('f64','double',8),('p0','ptr',8)]
s='''; RUN: llc -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s | FileCheck %s
; RUN: llc -O0 -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s -o /dev/null
; RUN: opt -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -passes=scalarize-masked-mem-intrin -S < %s | FileCheck %s --check-prefix=KEEP
; KEEP: call <2 x i8> @llvm.masked.gather
; KEEP: call void @llvm.masked.scatter.v16p0
; Generated by scripts/generate-masked-width-tests.py.
target triple = "x86_64-unknown-linux-gnu"
'''
header='/* Generated X-macro cases: K(lanes, type tag, bytes per element). */\n'
for lanes in [2,4,8,16]:
 for tag,ty,size in types:
  header+=f'K({lanes},{tag},{size})\n'
  for mode in ['idx','ptr','unaligned']:
   for op in ['g','s']:
    name=f'wide_{op}{lanes}_{tag}_{mode}';it=f'<{lanes} x {ty}>'
    s+=f'; CHECK-LABEL: {name}:\n'
    native=op=='g' and mode=='idx' and size==4
    s+='; CHECK: knc.vpgatherdd\n; CHECK: jne\n' if native else '; CHECK: bsfl\n; CHECK: jne\n'
    s+=f'define void @{name}(ptr %out,ptr %base,ptr %indices,ptr %values,ptr %maskptr) {{\n'
    s+=f' %mi=load <{lanes} x i32>,ptr %maskptr,align 4\n %mask=icmp ne <{lanes} x i32> %mi,zeroinitializer\n'
    if mode=='ptr':s+=f' %p=load <{lanes} x ptr>,ptr %indices,align 8\n'
    elif mode=='unaligned':s+=f' %ix=load <{lanes} x i64>,ptr %indices,align 8\n %p=getelementptr i8,ptr %base,<{lanes} x i64> %ix\n'
    else:s+=f' %ix=load <{lanes} x i32>,ptr %indices,align 4\n %p=getelementptr {ty},ptr %base,<{lanes} x i32> %ix\n'
    s+=f' %v=load {it},ptr %values,align 1\n'
    align=1 if mode=='unaligned' else size
    if op=='g':
     s+=f' %r=call {it} @llvm.masked.gather.v{lanes}{tag}.v{lanes}p0(<{lanes} x ptr> align {align} %p,<{lanes} x i1> %mask,{it} %v)\n store {it} %r,ptr %out,align 1\n'
    else:s+=f' call void @llvm.masked.scatter.v{lanes}{tag}.v{lanes}p0({it} %v,<{lanes} x ptr> align {align} %p,<{lanes} x i1> %mask)\n'
    s+=' ret void\n}\n'
  s+=f'declare {it} @llvm.masked.gather.v{lanes}{tag}.v{lanes}p0(<{lanes} x ptr>,<{lanes} x i1>,{it})\n'
  s+=f'declare void @llvm.masked.scatter.v{lanes}{tag}.v{lanes}p0({it},<{lanes} x ptr>,<{lanes} x i1>)\n'
(root/'tests/knc-masked-widths.ll').write_text(s)
(root/'tests/masked-widths-cases.h').write_text(header)
print('Generated 28 type/width combinations, three address modes, gather and scatter (168 kernels).')
