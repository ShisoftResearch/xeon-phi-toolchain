#!/usr/bin/env python3
"""Vector conversion matrix with exact rational, target-independent oracles."""
from pathlib import Path
from fractions import Fraction
import random
from ieee_oracle import decode, round_bits
root = Path(__file__).resolve().parents[1]
rng = random.Random(0x4b314f4d)
types = {'f32': 'float', 'f64': 'double', 'i32': 'i32', 'i64': 'i64'}
ops = [('fpext', 'f32', 'f64'), ('fptrunc', 'f64', 'f32')]
ops += [(op, a, b) for op in ('sitofp', 'uitofp') for a in ('i32', 'i64') for b in ('f32', 'f64')]
ops += [(op, a, b) for op in ('fptosi', 'fptoui') for a in ('f32', 'f64') for b in ('i32', 'i64')]
ir = '''; RUN: llc -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s | FileCheck %s
; RUN: llc -O0 -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s -o /dev/null
; RUN: llc -mcpu=knc -mattr=-sse,-sse2,+soft-float,-knc-native-abi -verify-machineinstrs < %s -o /dev/null
; Exercises folded extending loads, scalar fallback, native i32/f32 conversions,
; and split/widen legalization. Pointer ABI permits independent SDK harnesses.
target triple = "x86_64-unknown-linux-gnu"
'''
header = '/* Generated by generate-vector-conversion-tests.py. */\n'
corpus = '/* Independent exact rational conversion oracle. */\n'
rust = '// Generated SIMD cast clients; float-to-int inputs must satisfy simd_cast preconditions.\n'
for ty in ('f32', 'f64', 'i32', 'i64', 'u32', 'u64'):
    for n in (2, 4, 8, 16, 32):
        rust += f'#[repr(simd)]\n#[derive(Clone, Copy)]\nstruct V_{ty}_{n}([{ty}; {n}]);\n'
for op, src, dst in ops:
    a, b = int(src[1:]), int(dst[1:])
    name = f'{op}_{src}_{dst}'
    values = [0, 1, (1 << a) - 1, 1 << (a - 1)]
    if src[0] == 'f':
        frac, exp = (23, 8) if a == 32 else (52, 11)
        inf = ((1 << exp) - 1) << frac
        values += [inf, inf | (1 << (a-1)), inf-1, inf+1, inf+(1 << (frac-1)), 1 << frac, (1 << frac)-1]
        for k in range(-2, 66):
            for delta in (-1, 0, 1):
                for sign in (-1, 1):
                    v = round_bits(Fraction(sign * ((1 << max(k, 0)) + delta), 1 << max(-k, 0)), a)
                    values += [max(0, v-1), v, min((1 << a)-1, v+1)]
    else:
        for k in range(a):
            for d in (-1, 0, 1):
                values += [((1 << k)+d) & ((1 << a)-1), (-(1 << k)+d) & ((1 << a)-1)]
    values += [rng.getrandbits(a) for _ in range(2048)]
    rows = []
    for x in dict.fromkeys(values):
        if src[0] == 'i':
            v = x - (1 << a) if op == 'sitofp' and x >> (a-1) else x
            y = round_bits(Fraction(v), b)
        else:
            sign, kind, v = decode(x, a)
            if dst[0] == 'i':
                if kind != 'finite': continue
                y = int(v)  # LLVM conversion truncates toward zero; exclude poison.
                low, high = (-(1 << (b-1)), (1 << (b-1))-1) if op == 'fptosi' else (0, (1 << b)-1)
                if not low <= y <= high: continue
                y &= (1 << b)-1
            else:
                frac, exp = (23, 8) if b == 32 else (52, 11)
                if kind == 'nan': y = (((1 << exp)-1) << frac) | (1 << (frac-1))
                elif kind == 'inf': y = (sign << (b-1)) | (((1 << exp)-1) << frac)
                else: y = round_bits(v, b, sign)
        rows.append((x, y))
    corpus += f'static const struct sample data_{name}[] = {{\n'
    corpus += ''.join(f'{{UINT64_C(0x{x:x}), UINT64_C(0x{y:x})}},\n' for x,y in rows) + '};\n'
    for lanes in (2, 4, 8, 16, 32):
        fn = f'convert_{name}_{lanes}'
        ir += f'; CHECK-LABEL: {fn}:\n'
        if op in ('fpext', 'fptrunc'):
            mnemonic = 'vcvtps2pd' if op == 'fpext' else 'vcvtpd2ps'
            ir += f'; CHECK-NOT: callq\n; CHECK-COUNT-{(lanes+7)//8}: knc.{mnemonic}\n; CHECK-NOT: callq\n'
        elif (src,dst) in [('i32','f64'),('f64','i32')]:
            mnemonic={'sitofp':'vcvtdq2pd','uitofp':'vcvtudq2pd','fptosi':'vcvtfxpntpd2dq','fptoui':'vcvtfxpntpd2udq'}[op]
            ir += f'; CHECK-NOT: callq\n; CHECK-COUNT-{(lanes+7)//8}: knc.{mnemonic}\n; CHECK-NOT: callq\n'
        ir += f'''define void @{fn}(ptr %out, ptr %in) {{
 %x = load <{lanes} x {types[src]}>, ptr %in, align {a//8}
 %r = {op} <{lanes} x {types[src]}> %x to <{lanes} x {types[dst]}>
 store <{lanes} x {types[dst]}> %r, ptr %out, align {b//8}
 ret void
}}
'''
        header += f'K({fn}, {lanes}, {a//8}, {b//8}, {int(dst[0]=="f")}, data_{name})\n'
        rs = src.replace('i', 'u') if op == 'uitofp' else src
        rd = dst.replace('i', 'u') if op == 'fptoui' else dst
        rust += f"""#[no_mangle]
pub unsafe extern "C" fn {fn}(out: *mut u8, input: *const u8) {{
    let x = input.cast::<V_{rs}_{lanes}>().read_unaligned();
    let y: V_{rd}_{lanes} = core::intrinsics::simd::simd_cast(x);
    out.cast::<V_{rd}_{lanes}>().write_unaligned(y);
}}
"""

(root/'tests/knc-vector-conversions.ll').write_text(ir)
(root/'tests/vector-conversion-cases.h').write_text(header)
(root/'tests/vector-conversion-corpus.h').write_text(corpus)
(root/'rust-vector-math/src/conversions.rs').write_text(rust)
