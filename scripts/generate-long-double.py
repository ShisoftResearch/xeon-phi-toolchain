#!/usr/bin/env python3
"""Generate exact rational f80 arithmetic, cast and ABI references."""
from phi_common import RECORDS
RECORDS.mkdir(parents=True,exist_ok=True)
import hashlib,json,pathlib,random
from fractions import Fraction as F
import fp80_oracle as x
import ieee_oracle as ieee
root=pathlib.Path(__file__).resolve().parents[1];rng=random.Random(0x80cafe)
def bits(v):return x.round_bits(F(v))
def B(v):return '{UINT64_C(0x%016x),0x%04x}'%(v&((1<<64)-1),v>>64)
def U(v):return 'UINT64_C(0x%016x)'%v
def from_ieee(v,w):
 sign,tag,value=ieee.decode(v,w)
 return x.NAN if tag=='nan' else sign*x.SIGN|x.INF if tag=='inf' else x.round_bits(value,sign)
def to_ieee(v,w):
 tag,sign,value=x.decode(v);f,e={32:(23,8),64:(52,11)}[w]
 return (((1<<e)-1)<<f)|(1<<(f-1)) if tag=='nan' else (sign<<(w-1))|(((1<<e)-1)<<f) if tag=='inf' else ieee.round_bits(value,w,sign)
edges=[0,x.SIGN,1,x.SIGN|1,(1<<63)-1,x.SIGN|((1<<63)-1),1<<64|1<<63,bits(1),bits(-1),bits(2),bits(F(1)+x.pow2(-63)),bits(F(1)-x.pow2(-64)),bits(F(1)+x.pow2(-62)),bits(F(1<<63)-F(1,2)),bits(1<<63),bits((1<<64)-1),(0x7ffe<<64)|((1<<64)-1),x.INF,x.SIGN|x.INF,x.NAN,x.SIGN|x.NAN,x.INF|1,x.INF|0x123456789]
def random80():
 if rng.randrange(10)==0:return rng.choice(edges)
 ex=rng.choice([1,2,x.BIAS,x.BIAS-1000,x.BIAS-200,x.BIAS-1,x.BIAS+1,x.BIAS+200,x.BIAS+1000,0x7ffe]);return rng.randrange(2)*x.SIGN|ex<<64|1<<63|rng.getrandbits(63)
pairs=[(a,b) for a in edges for b in edges]
pairs += [(random80(),random80()) for _ in range(1024)]
# Cancellation and exact half-ULP cases at several scales.
for e in [-100,-1,0,1,100]:
 for k in range(64):pairs.append((bits(x.pow2(e)*(1+F(k,1<<63))),bits(-x.pow2(e))))
lines=['/* Generated by scripts/generate-long-double.py; independent exact rationals. */','struct fp80_bits{uint64_t sig;uint16_t se;};','struct fp80_case{struct fp80_bits a,b,out[5];unsigned comparison;uint64_t f64;uint32_t f32;};','static const struct fp80_case fp80_cases[]={']
for a,b in pairs:
 out=[x.binary(op,a,b) for op in ['add','sub','mul','div']]+[x.sqrt(a)]
 lines.append('{'+B(a)+','+B(b)+',{'+','.join(B(v) for v in out)+'},'+str(x.comparison(a,b))+','+U(to_ieee(a,64))+',UINT32_C(0x%08x)'%to_ieee(a,32)+'},')
lines+=['};','struct fp80_cast_case{uint64_t f64;uint32_t f32;struct fp80_bits wide64,wide32;};','static const struct fp80_cast_case fp80_cast_cases[]={']
cast_edges64=[0,1,0x8000000000000000,0x0010000000000000,0x3ff0000000000000,0x7fefffffffffffff,0x7ff0000000000000,0xfff0000000000000,0x7ff8000012345678,0x7ff0000000000001]
cast_edges32=[0,1,0x80000000,0x00800000,0x3f800000,0x7f7fffff,0x7f800000,0xff800000,0x7fc12345,0x7f800001]
for i in range(1034):
 a=cast_edges64[i] if i<10 else rng.getrandbits(64);b=cast_edges32[i] if i<10 else rng.getrandbits(32)
 lines.append('{'+U(a)+',UINT32_C(0x%08x),'%b+B(from_ieee(a,64))+','+B(from_ieee(b,32))+'},')
lines+=['};','struct fp80_int_case{uint64_t input;struct fp80_bits from_signed,from_unsigned,signed_arg,unsigned_arg;uint64_t signed_result,unsigned_result;};','static const struct fp80_int_case fp80_int_cases[]={']
int_edges=[0,1,(1<<63)-1,1<<63,(1<<64)-1,(1<<64)-2,0x8000000000000001]
for i in range(1031):
 raw=int_edges[i] if i<len(int_edges) else rng.getrandbits(64);signed=raw-(1<<64) if raw>>63 else raw
 signedarg=bits(F(signed,4));unsignedarg=bits(F(raw,4))
 if i==0:signedarg=bits(-(1<<63));unsignedarg=bits((1<<64)-1)
 if i==1:signedarg=bits(F(1<<63)-F(1,2));unsignedarg=bits(1<<63)
 sv=x.decode(signedarg)[2];uv=x.decode(unsignedarg)[2];assert -(1<<63)<=int(sv)<1<<63 and 0<=int(uv)<1<<64
 lines.append('{'+','.join([U(raw),B(bits(signed)),B(bits(raw)),B(signedarg),B(unsignedarg),U(int(sv)&((1<<64)-1)),U(int(uv))])+'},')
lines+=['};','struct fp80_abi_case{struct fp80_bits value,callback;};','static const struct fp80_abi_case fp80_abi_cases[]={']
for i in range(256):
 a=bits(F(1)+F(i,1<<63));lines.append('{'+B(a)+','+B(x.binary('add',a,bits(1)))+'},')
lines+=['};']
lines+=['struct fp80_small_case{unsigned width;uint32_t input;struct fp80_bits from_signed,from_unsigned,signed_arg,unsigned_arg;int64_t signed_result;uint64_t unsigned_result;};','static const struct fp80_small_case fp80_small_cases[]={']
for width in [8,16,32]:
 for i in range(256):
  raw=([0,1,(1<<(width-1))-1,1<<(width-1),(1<<width)-1][i] if i<5 else rng.getrandbits(width))
  signed=raw-(1<<width) if raw>>(width-1) else raw
  sa=bits(F(signed,2));ua=bits(F(raw,2));sv=int(x.decode(sa)[2]);uv=int(x.decode(ua)[2])
  lines.append('{'+str(width)+',UINT32_C(0x%08x),'%raw+','.join([B(bits(signed)),B(bits(raw)),B(sa),B(ua),str(sv),U(uv)])+'},')
lines+=['};']
path=root/'tests/long-double-corpus.h';path.write_text('\n'.join(lines)+'\n')
j={'oracle':'Exact rational arithmetic, independent nearest-even 64-significand-bit rounding and integer-square-root midpoint comparison; binary32/64 use independent IEEE rounding','arithmetic_pairs':len(pairs),'format_casts':1034,'integer_casts':1031,'small_casts':768,'abi_callbacks':256,'source_sha256':{p:hashlib.sha256((root/p).read_bytes()).hexdigest() for p in ['scripts/fp80_oracle.py','scripts/ieee_oracle.py','scripts/generate-long-double.py']},'corpus_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'domain':'Canonical defined x87 extended encodings, including subnormals, signed zero, infinities, quiet/signaling NaNs; NaN results classified without payload promises; integer casts only in defined domain; default RNE/64-bit precision'}
(RECORDS/'long-double-oracle.json').write_text(json.dumps(j,indent=2)+'\n');print('Generated f80 corpus',len(pairs),'arithmetic pairs, 1034 format casts, 1031 integer rows, 256 callbacks')
