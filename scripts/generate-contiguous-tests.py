#!/usr/bin/env python3
"""Generate the contiguous masked-memory width/type regression matrix."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
types=[('i8','i8',1),('i16','i16',2),('i32','i32',4),('i64','i64',8),('f32','float',4),('f64','double',8),('p0','ptr',8)]
s='''; RUN: llc -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s | FileCheck %s
; RUN: llc -O0 -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s -o /dev/null
; RUN: opt -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -passes=scalarize-masked-mem-intrin -S < %s | FileCheck %s --check-prefix=KEEP
; KEEP: call <2 x i8> @llvm.masked.load
; KEEP: call void @llvm.masked.store.v16p0
; Generated by scripts/generate-contiguous-tests.py.
target triple = "x86_64-unknown-linux-gnu"
'''
h='/* Generated X-macro matrix: K(lanes, element tag, bytes). */\n'
for n in [2,4,8,16]:
 for tag,ty,b in types:
  h+=f'K({n},{tag},{b})\n';v=f'<{n} x {ty}>'
  for mode in ['aligned','unaligned']:
   for op in ['load','store']:
    name=f'contig_{op}{n}_{tag}_{mode}';native=b==4 and mode=='aligned'
    s+=f'; CHECK-LABEL: {name}:\n'
    s+=f'; CHECK: knc.vp{"gather" if op=="load" else "scatter"}dd\n; CHECK: jne\n' if native else '; CHECK: bsfl\n; CHECK: jne\n'
    s+=f'define void @{name}(ptr %out,ptr %base,ptr %values,ptr %maskptr) {{\n %mi=load <{n} x i32>,ptr %maskptr,align 4\n %mask=icmp ne <{n} x i32> %mi,zeroinitializer\n %v=load {v},ptr %values,align 1\n'
    align=b if mode=='aligned' else 1
    if op=='load':s+=f' %r=call {v} @llvm.masked.load.v{n}{tag}.p0(ptr align {align} %base,<{n} x i1> %mask,{v} %v)\n store {v} %r,ptr %out,align 1\n'
    else:s+=f' call void @llvm.masked.store.v{n}{tag}.p0({v} %v,ptr align {align} %base,<{n} x i1> %mask)\n'
    s+=' ret void\n}\n'
  s+=f'declare {v} @llvm.masked.load.v{n}{tag}.p0(ptr,<{n} x i1>,{v})\n'
  s+=f'declare void @llvm.masked.store.v{n}{tag}.p0({v},ptr,<{n} x i1>)\n'
# Compose masked loads/stores with integer extension/truncation to exercise DAG folds.
for narrow in [8,16,32]:
 for wide in [32,64]:
  if narrow>=wide:continue
  for sign in ['s','u']:
   name=f'contig_extend_{sign}{narrow}_{wide}'
   s+=f'define void @{name}(ptr %out,ptr %base,ptr %values,ptr %maskptr) {{\n %mi=load <16 x i32>,ptr %maskptr,align 4\n %mask=icmp ne <16 x i32> %mi,zeroinitializer\n %p=load <16 x i{narrow}>,ptr %values,align 1\n %r=call <16 x i{narrow}> @llvm.masked.load.v16i{narrow}.p0(ptr align 1 %base,<16 x i1> %mask,<16 x i{narrow}> %p)\n %e={"sext" if sign=="s" else "zext"} <16 x i{narrow}> %r to <16 x i{wide}>\n store <16 x i{wide}> %e,ptr %out,align 1\n ret void\n}}\n'
  name=f'contig_truncate_{wide}_{narrow}'
  s+=f'define void @{name}(ptr %out,ptr %base,ptr %values,ptr %maskptr) {{\n %mi=load <16 x i32>,ptr %maskptr,align 4\n %mask=icmp ne <16 x i32> %mi,zeroinitializer\n %v=load <16 x i{wide}>,ptr %values,align 1\n %t=trunc <16 x i{wide}> %v to <16 x i{narrow}>\n call void @llvm.masked.store.v16i{narrow}.p0(<16 x i{narrow}> %t,ptr align 1 %base,<16 x i1> %mask)\n ret void\n}}\n'
(root/'tests/knc-contiguous.ll').write_text(s)
(root/'tests/contiguous-cases.h').write_text(h)
print('Generated 112 contiguous kernels and 15 extension/truncation compositions.')
