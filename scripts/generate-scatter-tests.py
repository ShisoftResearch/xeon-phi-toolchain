#!/usr/bin/env python3
"""Generate constant-index scatter candidates and deliberately rejected paths."""
import pathlib
root=pathlib.Path(__file__).resolve().parents[1];cases=[]
for n in [2,4,8,16]:
 for ty in ['i32','float']:
  for iw in [32,64]:
   for pattern,indices in [('stride',[i*3+1 for i in range(n)]),('reverse',[3*(n-i)-2 for i in range(n)]),('negative',[-i*3-1 for i in range(n)])]:
    cases.append(dict(name=f'scatter_{n}_{ty}_{iw}_{pattern}',n=n,ty=ty,iw=iw,indices=indices,scale=4,align=4,native=1,dynamic=0))
for name,ty,iw,indices,scale,align,dynamic in [
 ('duplicate','i32',32,[i//2 for i in range(16)],4,4,0),
 ('partial','i32',32,[i*3 for i in range(16)],1,1,0),
 ('scale2','i32',32,list(range(16)),2,2,0),
 ('unaligned','float',32,[i*3+1 for i in range(16)],4,1,0),
 ('wideindex','i32',64,[0]+[2147483648+i*1024 for i in range(15)],4,4,0),
 ('negativewide','float',64,[0]+[-2147483649-i*1024 for i in range(15)],4,4,0),
 ('i64','i64',32,[i*3+1 for i in range(16)],8,8,0),
 ('f64','double',32,[i*3+1 for i in range(16)],8,8,0),
 ('dynamic','i32',32,[i*3+1 for i in range(16)],4,4,1)]:
 cases.append(dict(name='scatter_reject_'+name,n=16,ty=ty,iw=iw,indices=indices,scale=scale,align=align,native=0,dynamic=dynamic))
lines=['; Generated by scripts/generate-scatter-tests.py.','; RUN: llc -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s | FileCheck %s',
 '; RUN: llc -knc-disjoint-scatter=false -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s | FileCheck %s --check-prefix=OFF',
 '; RUN: llc -O0 -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s -o /dev/null','target triple = "x86_64-unknown-linux-gnu"']
headers=[];decls=set()
for c in cases:
 name,n,ty,iw=c['name'],c['n'],c['ty'],c['iw'];candidate=c['native'];c['native']=candidate and n>=8;bits=64 if ty in ['i64','double'] else 32;vt=f'<{n} x {ty}>';it=f'<{n} x i{iw}>';mt=f'<{n} x i1>'
 suffix={'float':'f32','double':'f64'}.get(ty,ty);intr=f'llvm.masked.scatter.v{n}{suffix}.v{n}p0';decls.add(f'declare void @{intr}({vt}, <{n} x ptr>, {mt})')
 lines += [f'; CHECK-LABEL: {name}:']
 lines += ['; CHECK: knc.vpscatterdd','; CHECK-NEXT: kmovw','; CHECK-NEXT: testl','; CHECK-NEXT: jne','; CHECK-NOT: bsfl'] if c['native'] else ['; CHECK-NOT: knc.vpscatterdd','; CHECK: bsfl']
 lines += ['; CHECK: retq',f'; OFF-LABEL: {name}:','; OFF-NOT: knc.vpscatterdd','; OFF: bsfl','; OFF: retq',f'define void @{name}(ptr %base, ptr %values, ptr %masks, ptr %indices) {{',f' %v = load {vt}, ptr %values, align 1',f' %m = load <{n} x i32>, ptr %masks, align 1',f' %mask = icmp ne <{n} x i32> %m, zeroinitializer']
 if c['dynamic']:lines.append(f' %ix = load {it}, ptr %indices, align 1');ix='%ix'
 else:ix='<'+', '.join(f'i{iw} {i}' for i in c['indices'])+'>'
 lines += [f' %p = getelementptr i{c["scale"]*8}, ptr %base, {it} {ix}',f' call void @{intr}({vt} %v, <{n} x ptr> align {c["align"]} %p, {mt} %mask)',' ret void','}']
 headers.append('K('+','.join(map(str,[name,n,bits//8,c['scale'],c['align'],int(candidate),int(c['native']),iw,c['dynamic'],*c['indices']]))+')')
lines+=sorted(decls)
(root/'tests/knc-disjoint-scatter.ll').write_text('\n'.join(lines)+'\n');(root/'tests/scatter-cases.h').write_text('/* Generated scatter contracts; offsets are element indices, not bytes. */\n'+'\n'.join(headers)+'\n')
print('Generated',len(cases),'scatter kernels:',sum(c['native'] for c in cases),'profitable proven disjoint paths')
