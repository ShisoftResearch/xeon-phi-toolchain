#!/usr/bin/env python3
"""Bounded independent-chain arithmetic for before/after scheduler evaluation."""
import pathlib
root=pathlib.Path(__file__).resolve().parents[1]
ir=['; RUN: llc -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s -o /dev/null','target triple = "x86_64-unknown-linux-gnu"'];cases=[]
for width,ty,lanes in [(32,'float',16),(64,'double',8)]:
    vt=f'<{lanes} x {ty}>'
    for kind in ['add','mul','fma','mixed']:
        for chains in [1,2,4,8]:
            for depth in [8,32]:
                name=f'schedule_{kind}_{width}_{chains}_{depth}';cases.append(f'K({name},{width},{chains},{depth},{["add","mul","fma","mixed"].index(kind)})')
                ir.append(f'define void @{name}(ptr %out,ptr %in) {{')
                for i in range(chains+2):
                    ir += [f' %p{i}=getelementptr i8,ptr %in,i64 {i*64}',f' %v{i}=load {vt},ptr %p{i},align 64']
                values=[f'%v{i}' for i in range(chains)]
                for step in range(depth):
                    for chain in range(chains):
                        op=kind if kind!='mixed' else ['fma','add','mul','sub'][step%4]
                        result=f'%r{step}_{chain}'
                        if op=='fma':text=f'call {vt} @llvm.fma.v{lanes}f{width}({vt} {values[chain]},{vt} %v{chains},{vt} %v{chains+1})'
                        else:text=f'f{op} {vt} {values[chain]},%v{chains}'
                        ir.append(f' {result}={text}');values[chain]=result
                for i,v in enumerate(values):ir += [f' %out{i}=getelementptr i8,ptr %out,i64 {i*64}',f' store {vt} {v},ptr %out{i},align 64']
                ir += [' ret void','}']
    ir.append(f'declare {vt} @llvm.fma.v{lanes}f{width}({vt},{vt},{vt})')
(root/'tests/knc-fp-scheduling-workloads.ll').write_text('\n'.join(ir)+'\n')
(root/'tests/fp-scheduling-cases.h').write_text('/* Generated by generate-fp-scheduling.py. */\n'+'\n'.join(cases)+'\n')
print('Generated',len(cases),'same-IR scheduling comparisons')
test=['; REQUIRES: asserts',"; RUN: llc -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -debug-only=machine-scheduler < %s -o /dev/null 2>&1 | FileCheck %s --check-prefix=ON", "; RUN: llc -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -knc-fp-scheduling=false -debug-only=machine-scheduler < %s -o /dev/null 2>&1 | FileCheck %s --check-prefix=OFF",'target triple = "x86_64-unknown-linux-gnu"']
for width,ty,lanes in [(32,'float',16),(64,'double',8)]:
    vt=f'<{lanes} x {ty}>'
    for op,machine in [('add','VADD'),('sub','VSUB'),('mul','VMUL'),('fma','VFMADD132')]:
        opcode='KNC_'+machine+('PS' if width==32 else 'PD')+('rr' if op!='fma' else '')
        test += [f'; ON: SU({{{{[0-9]+}}}}): {{{{.*}}}}{opcode}','; ON: Latency            : 4',f'; OFF: SU({{{{[0-9]+}}}}): {{{{.*}}}}{opcode}','; OFF: Latency            : 0',f'define void @latency_{op}_{width}(ptr %out,ptr %a,ptr %b,ptr %c) {{',f' %x=load {vt},ptr %a,align 64',f' %y=load {vt},ptr %b,align 64',f' %z=load {vt},ptr %c,align 64']
        operation=f'call {vt} @llvm.fma.v{lanes}f{width}({vt} %x,{vt} %y,{vt} %z)' if op=='fma' else f'f{op} {vt} %x,%y'
        test += [f' %r={operation}',f' store {vt} %r,ptr %out,align 64',' ret void','}']
    test.append(f'declare {vt} @llvm.fma.v{lanes}f{width}({vt},{vt},{vt})')
for name,opcode in [('rcp23','KNC_VRCP23PS'),('rsqrt23','KNC_VRSQRT23PS')]:
    test += [f'; ON: SU({{{{[0-9]+}}}}): {{{{.*}}}}{opcode}','; ON: Latency            : 6',f'; OFF: SU({{{{[0-9]+}}}}): {{{{.*}}}}{opcode}','; OFF: Latency            : 0',f'define void @latency_{name}(ptr %out,ptr %a) {{',' %x=load <16 x float>,ptr %a,align 64',f' %r=call <16 x float> @llvm.x86.knc.{name}.ps(<16 x float> %x)',' store <16 x float> %r,ptr %out,align 64',' ret void','}',f'declare <16 x float> @llvm.x86.knc.{name}.ps(<16 x float>)']
(root/'tests/knc-fp-scheduling.ll').write_text('\n'.join(test)+'\n')
