#!/usr/bin/env python3
"""A backend feasibility probe, not a change to default scalar lowering.

Compare the current scalar helper path with legal full-register FP arithmetic
and integer bit transport across the existing native scalar ABI. Compile with
llc directly: an IR optimizer may scalarize this experimental construction.
"""
import pathlib
root=pathlib.Path(__file__).resolve().parents[1]
lines=['; Generated by scripts/generate-scalar-fp-evaluation.py.',
       '; Experimental scalar-through-vector recipes, not default lowering.',
       'target triple = "x86_64-unknown-linux-gnu"']
for width,elt,n in [(32,'float',16),(64,'double',8)]:
    it=f'i{width}';iv=f'<{n} x {it}>';fv=f'<{n} x {elt}>'
    for op in ['add','sub','mul']:
        lines += [f'define {elt} @soft_{op}_value_f{width}({elt} %a,{elt} %b) #0 {{',
                  f' %r=f{op} {elt} %a,%b',f' ret {elt} %r','}']
        lines.append(f'define {elt} @native_{op}_value_f{width}({elt} %a,{elt} %b) {{')
        for x in ['a','b']:
            lines += [f' %{x}i=bitcast {elt} %{x} to {it}',
              f' %{x}0=insertelement {iv} poison,{it} %{x}i,i32 0',
              f' %{x}s=shufflevector {iv} %{x}0,{iv} poison,<{n} x i32> zeroinitializer',
              f' %{x}v=bitcast {iv} %{x}s to {fv}']
        lines += [f' %r=f{op} {fv} %av,%bv',f' %ri=bitcast {fv} %r to {iv}',
                  f' %i=extractelement {iv} %ri,i32 0',f' %f=bitcast {it} %i to {elt}',f' ret {elt} %f','}']
lines.append('attributes #0 = { "target-features"="+knc-native-abi,-sse,-sse2,+soft-float,-knc-scalar-fp" }')
(root/'tests/knc-scalar-fp-evaluation.ll').write_text('\n'.join(lines)+'\n')
