#!/usr/bin/env python3
"""Regenerate the matcher from the pinned capability snapshot (not new hardware proof)."""
import hashlib,json,pathlib,types
root=pathlib.Path(__file__).resolve().parents[1]
manifest=json.loads((root/'capabilities/k1om.json').read_text())
keys=['schema_version','target','register_bytes','vector_registers','operations','types','properties','assumptions','layouts','known_absent_native','capabilities','contract']
payload={k:manifest[k] for k in keys}
digest=hashlib.sha256(json.dumps(payload,sort_keys=True,separators=(',',':')).encode()).hexdigest()
if digest!=manifest['catalog_sha256']:
 raise SystemExit('Capability snapshot changed; establish and record new contracts before exporting')
rows=manifest['capabilities']
catalog=types.SimpleNamespace(**{k.upper():manifest[k] for k in ['types','operations','layouts','properties','assumptions']},ABSENT=manifest['known_absent_native'])
def enum(prefix,names):return 'enum {\n'+''.join(f'  {prefix}{name.upper()} = {i},\n' for i,name in enumerate(names))+f'  {prefix}COUNT = {len(names)}\n}};\n'
def flags(prefix,names):return 'enum {\n'+''.join(f'  {prefix}{name} = 1u << {i},\n' for i,name in enumerate(names))+'};\n'
h='''/* Generated by scripts/generate-capability-catalog.py. Do not edit.
 * This is a K1OM capability catalog and requirement matcher, not an ISA shim. */
#ifndef K1OM_CAPABILITIES_H
#define K1OM_CAPABILITIES_H
#include <stddef.h>
#include <stdint.h>
#ifdef __cplusplus
#define K1OM_CE constexpr
#define K1OM_DATA static constexpr
#else
#define K1OM_CE
#define K1OM_DATA static const
#endif
#define K1OM_CATALOG_VERSION 1
'''
h+=f'#define K1OM_CATALOG_SHA256 "{digest}"\n'
h+=enum('K1OM_TYPE_',catalog.TYPES)+enum('K1OM_OP_',catalog.OPERATIONS)+enum('K1OM_LAYOUT_',catalog.LAYOUTS)
h+=flags('K1OM_PROP_',catalog.PROPERTIES)+flags('K1OM_ASSUME_',catalog.ASSUMPTIONS)
h+='''enum { K1OM_PATH_NONE=0, K1OM_PATH_NATIVE=1, K1OM_PATH_COMPOSED=2, K1OM_PATH_RUNTIME=3 };
enum { K1OM_ALLOW_NATIVE=1u<<K1OM_PATH_NATIVE, K1OM_ALLOW_COMPOSED=1u<<K1OM_PATH_COMPOSED,
       K1OM_ALLOW_RUNTIME=1u<<K1OM_PATH_RUNTIME,
       K1OM_ALLOW_DEFAULT=K1OM_ALLOW_NATIVE|K1OM_ALLOW_COMPOSED,
       K1OM_ALLOW_ANY=K1OM_ALLOW_DEFAULT|K1OM_ALLOW_RUNTIME };
enum { K1OM_MATCH_OK=0, K1OM_MATCH_INVALID=1, K1OM_MATCH_NATIVE_ABSENT=2,
       K1OM_MATCH_SHAPE_UNVERIFIED=3, K1OM_MATCH_SEMANTICS_UNVERIFIED=4,
       K1OM_MATCH_PRECONDITION_REQUIRED=5, K1OM_MATCH_ALIGNMENT_REQUIRED=6,
       K1OM_MATCH_PATH_DISALLOWED=7, K1OM_MATCH_TARGET_MISMATCH=8 };
typedef struct {
 unsigned operation,input_type,output_type,input_lanes,output_lanes;
 unsigned alignment,layout,properties,assumptions;
} k1om_requirement;
typedef struct {
 unsigned operation,input_type,output_type,input_lanes,output_lanes;
 unsigned alignment,layout,properties,preconditions,path;
 const char *proof,*case_name;
} k1om_capability;
typedef struct {
 unsigned status,path,available_paths;
 const k1om_capability *capability;
} k1om_match;
typedef struct { unsigned status,path; size_t failed_requirement; } k1om_plan_match;
'''
h+='K1OM_DATA k1om_capability k1om_capabilities[] = {\n'
for row in rows:
    props='|'.join('K1OM_PROP_'+p for p in row['properties']) or '0';pre='|'.join('K1OM_ASSUME_'+p for p in row['assumptions']) or '0'
    h+=' {K1OM_OP_%s,K1OM_TYPE_%s,K1OM_TYPE_%s,%d,%d,%d,K1OM_LAYOUT_%s,%s,%s,K1OM_PATH_%s,%s,%s},\n'%(row['operation'].upper(),row['input_type'],row['output_type'],row['input_lanes'],row['output_lanes'],row['alignment'],row['layout'],props,pre,row['path'],json.dumps(row['proof']),json.dumps(row['case']))
h+='};\n#define K1OM_CAPABILITY_COUNT (sizeof(k1om_capabilities)/sizeof(k1om_capabilities[0]))\n'
h+=f'#define K1OM_KNOWN_PROPERTIES ((1u<<{len(catalog.PROPERTIES)})-1u)\n#define K1OM_KNOWN_ASSUMPTIONS ((1u<<{len(catalog.ASSUMPTIONS)})-1u)\n'
h+='''static inline K1OM_CE int k1om_compiler_target(void) {
#if defined(__k1om__)
 return 1;
#else
 return 0;
#endif
}
static inline K1OM_CE k1om_requirement k1om_require(unsigned op,unsigned input,unsigned output,unsigned lanes,unsigned out_lanes) {
 k1om_requirement r={op,input,output,lanes,out_lanes,0,K1OM_LAYOUT_NONE,0,0};return r;
}
/* Catalog queries support explicit cross-target planning. They do not assert
 * that the current CPU or compiled program is K1OM. Use target_query to gate
 * execution in a target build. No data pointers are accepted by this API. */
static inline K1OM_CE k1om_match k1om_catalog_query(k1om_requirement r,unsigned allowed) {
 k1om_match result={K1OM_MATCH_INVALID,K1OM_PATH_NONE,0,0};
 if(r.operation>=K1OM_OP_COUNT||r.input_type==K1OM_TYPE_NONE||r.input_type>=K1OM_TYPE_COUNT||
    r.output_type==K1OM_TYPE_NONE||r.output_type>=K1OM_TYPE_COUNT||!r.input_lanes||!r.output_lanes||
    r.layout>=K1OM_LAYOUT_COUNT||(r.alignment&&(r.alignment&(r.alignment-1)))||
    (r.properties&~K1OM_KNOWN_PROPERTIES)||(r.assumptions&~K1OM_KNOWN_ASSUMPTIONS)||
    !allowed||(allowed&~K1OM_ALLOW_ANY))return result;
'''
for op in catalog.ABSENT:h+=f' if(r.operation==K1OM_OP_{op.upper()}){{result.status=K1OM_MATCH_NATIVE_ABSENT;return result;}}\n'
h+=''' unsigned shape=0,semantic=0,precondition=0,aligned=0;
 for(size_t i=0;i<K1OM_CAPABILITY_COUNT;++i){
  const k1om_capability *c=&k1om_capabilities[i];
  if(c->operation!=r.operation||c->input_type!=r.input_type||c->output_type!=r.output_type||
     c->input_lanes!=r.input_lanes||c->output_lanes!=r.output_lanes||c->layout!=r.layout)continue;
  shape=1;if((r.properties&c->properties)!=r.properties)continue;
  semantic=1;if((r.assumptions&c->preconditions)!=c->preconditions)continue;
  precondition=1;if(r.alignment<c->alignment)continue;
  aligned=1;result.available_paths|=1u<<c->path;
  if((allowed&(1u<<c->path))&&(!result.capability||c->path<result.path)){
   result.capability=c;result.path=c->path;
  }
 }
 if(result.capability)result.status=K1OM_MATCH_OK;
 else if(!shape)result.status=K1OM_MATCH_SHAPE_UNVERIFIED;
 else if(!semantic)result.status=K1OM_MATCH_SEMANTICS_UNVERIFIED;
 else if(!precondition)result.status=K1OM_MATCH_PRECONDITION_REQUIRED;
 else if(!aligned)result.status=K1OM_MATCH_ALIGNMENT_REQUIRED;
 else result.status=K1OM_MATCH_PATH_DISALLOWED;
 return result;
}
static inline K1OM_CE k1om_match k1om_target_query(k1om_requirement r,unsigned allowed) {
 if(!k1om_compiler_target()){
  k1om_match m={K1OM_MATCH_TARGET_MISMATCH,K1OM_PATH_NONE,0,0};return m;
 }
 return k1om_catalog_query(r,allowed);
}
/* Match a proposed algorithm's prerequisites. This never constructs, executes
 * or substitutes an implementation. The application owns the native kernel. */
static inline K1OM_CE k1om_plan_match k1om_catalog_match_requirements(const k1om_requirement *requirements,size_t count,unsigned allowed){
 k1om_plan_match result={K1OM_MATCH_INVALID,K1OM_PATH_NONE,0};
 if(!requirements||!count||!allowed||(allowed&~K1OM_ALLOW_ANY))return result;
 for(size_t i=0;i<count;++i){
  k1om_match m=k1om_catalog_query(requirements[i],allowed);
  if(m.status!=K1OM_MATCH_OK){result.status=m.status;result.failed_requirement=i;return result;}
  if(m.path>result.path)result.path=m.path;
 }
 result.status=K1OM_MATCH_OK;result.failed_requirement=(size_t)-1;return result;
}
static inline K1OM_CE k1om_plan_match k1om_target_match_requirements(const k1om_requirement *requirements,size_t count,unsigned allowed){
 if(!k1om_compiler_target()){
  k1om_plan_match result={K1OM_MATCH_TARGET_MISMATCH,K1OM_PATH_NONE,0};return result;
 }
 return k1om_catalog_match_requirements(requirements,count,allowed);
}
static inline K1OM_CE const char *k1om_match_diagnostic(unsigned status){
 switch(status){
 case K1OM_MATCH_OK:return "verified K1OM capability match";
 case K1OM_MATCH_INVALID:return "invalid K1OM capability request";
 case K1OM_MATCH_NATIVE_ABSENT:return "native K1OM feature absent; application kernel must use different primitives";
 case K1OM_MATCH_SHAPE_UNVERIFIED:return "no verified K1OM capability for this shape or layout";
 case K1OM_MATCH_SEMANTICS_UNVERIFIED:return "requested numerical, mask or memory semantics are unverified";
 case K1OM_MATCH_PRECONDITION_REQUIRED:return "caller must establish the capability's domain preconditions";
 case K1OM_MATCH_ALIGNMENT_REQUIRED:return "guaranteed alignment is insufficient for the verified path";
 case K1OM_MATCH_PATH_DISALLOWED:return "available K1OM paths are excluded by the caller's policy";
 case K1OM_MATCH_TARGET_MISMATCH:return "current compiler target is not K1OM; use catalog queries only for planning";
 default:return "unknown K1OM match status";
 }
}
#undef K1OM_CE
#undef K1OM_DATA
#endif
'''
(root/'include/k1om/capabilities.h').write_text(h)
print('Generated',len(rows),'K1OM capability contracts;',digest)
