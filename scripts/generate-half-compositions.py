#!/usr/bin/env python3
"""FP16/FP32/FP64 pointer-ABI casts and masked conversion compositions."""
from pathlib import Path
from fractions import Fraction
import random
from ieee_oracle import decode,round_bits
root=Path(__file__).resolve().parents[1]
s='''; RUN: llc -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s -o /dev/null
; RUN: llc -O0 -mcpu=knc -mattr=-sse,-sse2,+soft-float,+knc-native-abi -verify-machineinstrs < %s -o /dev/null
target triple = "x86_64-unknown-linux-gnu"
'''
h='/* Generated by generate-half-compositions.py. */\n';decls=set()
for n in (2,4,8,16,32):
 for wide,ty in ((32,'float'),(64,'double')):
  for shape in ('plain','contig','indexed'):
   for align in ((1,) if shape=='plain' else (1,2)):
    for store in (0,1):
     name=f'half_comp_{n}_{wide}_{shape}_{align}_{store}'
     s+=f'define void @{name}(ptr %out,ptr %base,ptr %values,ptr %mp) {{\n'
     if shape!='plain':
      s+=f' %mi=load <{n} x i32>,ptr %mp,align 4\n %mask=icmp ne <{n} x i32> %mi,zeroinitializer\n'
     indexed=shape=='indexed';suffix=f'v{n}p0' if indexed else 'p0'
     if indexed:s+=f' %ptrs=load <{n} x ptr>,ptr %base,align 8\n'
     args=f'<{n} x ptr> %ptrs,i32 {align}' if indexed else f'ptr align {align} %base'
     if not store:
      if shape=='plain':s+=f' %h=load <{n} x half>,ptr %base,align 1\n'
      else:
       op='gather' if indexed else 'load'
       s+=f' %pass=load <{n} x half>,ptr %values,align 1\n %h=call <{n} x half> @llvm.masked.{op}.v{n}f16.{suffix}({args},<{n} x i1> %mask,<{n} x half> %pass)\n'
       decls.add(f'declare <{n} x half> @llvm.masked.{op}.v{n}f16.{suffix}('+(f'<{n} x ptr>,i32 immarg' if indexed else 'ptr')+f',<{n} x i1>,<{n} x half>)\n')
      s+=f' %r=fpext <{n} x half> %h to <{n} x {ty}>\n store <{n} x {ty}> %r,ptr %out,align 1\n'
     else:
      s+=f' %x=load <{n} x {ty}>,ptr %values,align 1\n %h=fptrunc <{n} x {ty}> %x to <{n} x half>\n'
      if shape=='plain':s+=f' store <{n} x half> %h,ptr %base,align 1\n'
      else:
       op='scatter' if indexed else 'store'
       s+=f' call void @llvm.masked.{op}.v{n}f16.{suffix}(<{n} x half> %h,{args},<{n} x i1> %mask)\n'
       decls.add(f'declare void @llvm.masked.{op}.v{n}f16.{suffix}(<{n} x half>,'+(f'<{n} x ptr>,i32 immarg' if indexed else 'ptr')+f',<{n} x i1>)\n')
     s+=' ret void\n}\n'
     h+=f'K({name},{n},{wide},{int(shape=="plain")},{int(indexed)},{align},{store})\n'
s+=''.join(sorted(decls))
(root/'tests/knc-half-compositions.ll').write_text(s)
(root/'tests/half-composition-cases.h').write_text(h)
corpus='/* Exact rational nearest-even wide-to-half oracle; unconstrained NaNs classified separately. */\n'
rng=random.Random(0x16c0a57)
for w in (32,64):
 f,e=(23,8) if w==32 else (52,11);inf=((1<<e)-1)<<f
 vals=[0,1,(1<<w)-1,1<<(w-1),inf,inf|(1<<(w-1)),inf-1,inf+1,inf+(1<<(f-1))]
 for k in range(-26,18):
  for num in (1,3,1023,1024,1025,2047):
   value=Fraction(num)*(Fraction(2)**k)
   for sign in (-1,1):
    v=round_bits(sign*value,w)
    vals.extend([max(0,v-1),v,min((1<<w)-1,v+1)])
 vals += [rng.getrandbits(w) for _ in range(4096)]
 rows=[]
 for x in dict.fromkeys(vals):
  sign,kind,v=decode(x,w)
  y=0x7e00 if kind=='nan' else (sign<<15)|0x7c00 if kind=='inf' else round_bits(v,16,sign)
  rows.append((x,y))
 corpus+=f'static const struct half_case data{w}[]={{\n'+''.join(f'{{UINT64_C(0x{x:x}),0x{y:x}}},\n' for x,y in rows)+'};\n'
(root/'tests/half-composition-corpus.h').write_text(corpus)
